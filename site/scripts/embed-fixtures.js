import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const dir = dirname(fileURLToPath(import.meta.url));
const root = join(dir, "..");
const dataDir = join(root, "..", "data");

let events = "";
let recordsFallback = "";
try {
  events = readFileSync(join(dataDir, "events.ndjson"), "utf8").trim();
} catch {
  console.warn("No data/events.ndjson — production embed will use records fallback only");
}
try {
  recordsFallback = readFileSync(join(dataDir, "records.ndjson"), "utf8").trim();
} catch {
  /* optional */
}

let offers = "";
try {
  offers = readFileSync(join(dataDir, "offers.ndjson"), "utf8").trim();
} catch {
  /* optional: GO D1 offers */
}

let synth = "";
try {
  synth = readFileSync(join(root, "fixtures/records.synthetic.ndjson"), "utf8");
} catch {
  /* */
}

// Verify every embedded event here (id + Schnorr sig) so the Worker does not spend CPU re-verifying on each cold start
// (that cost caused Cloudflare 1102 "Worker exceeded resource limits"). A bad event fails the build.
import * as secp from "@noble/secp256k1";
import { sha256 } from "@noble/hashes/sha2.js";
import { hmac } from "@noble/hashes/hmac.js";
import { bytesToHex, hexToBytes, utf8ToBytes } from "@noble/hashes/utils.js";
if (secp.hashes) { secp.hashes.sha256 = sha256; secp.hashes.hmacSha256 = (k, ...m) => hmac(sha256, k, secp.etc.concatBytes(...m)); }
let verified = 0;
for (const line of events.split("\n")) {
  if (!line.trim()) continue;
  const ev = JSON.parse(line);
  const id = bytesToHex(sha256(utf8ToBytes(JSON.stringify([0, ev.pubkey, ev.created_at, ev.kind, ev.tags, ev.content]))));
  if (id !== ev.id || !secp.schnorr.verify(hexToBytes(ev.sig), hexToBytes(ev.id), hexToBytes(ev.pubkey))) {
    console.error("embed-fixtures: invalid event", ev.id); process.exit(1);
  }
  verified++;
}
const out = `/** Generated by scripts/embed-fixtures.js — do not edit */
export const EMBEDDED_EVENTS_NDJSON = ${JSON.stringify(events)};
/** Every event above was id- and signature-checked at build time (${verified} events). */
export const EMBEDDED_EVENTS_VERIFIED_AT_BUILD = ${verified > 0};
export const EMBEDDED_RECORDS_FALLBACK_NDJSON = ${JSON.stringify(recordsFallback)};
export const EMBEDDED_OFFERS_NDJSON = ${JSON.stringify(offers)};
export const EMBEDDED_SYNTHETIC_NDJSON = ${JSON.stringify(synth.trim())};
/** @deprecated use EMBEDDED_EVENTS_NDJSON */
export const EMBEDDED_FIXTURE_NDJSON = EMBEDDED_EVENTS_NDJSON || EMBEDDED_RECORDS_FALLBACK_NDJSON;
`;
writeFileSync(join(root, "worker/src/fixture-data.ts"), out);
console.log(`Verified ${verified} embedded events at build time`);
console.log(
  "Embedded",
  events ? events.split("\n").length : 0,
  "events,",
  recordsFallback ? recordsFallback.split("\n").length : 0,
  "record fallback lines,",
  synth.trim() ? synth.trim().split("\n").length : 0,
  "synthetic",
);
