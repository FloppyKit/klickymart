import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const dir = dirname(fileURLToPath(import.meta.url));
const root = join(dir, "..");
const sample = readFileSync(join(root, "fixtures/records.sample.ndjson"), "utf8");
let synth = "";
try {
  synth = readFileSync(join(root, "fixtures/records.synthetic.ndjson"), "utf8");
} catch {
  /* */
}
const combined = [sample.trim(), synth.trim()].filter(Boolean).join("\n");
const out = `/** Generated by scripts/embed-fixtures.js — do not edit */\nexport const EMBEDDED_FIXTURE_NDJSON = ${JSON.stringify(combined)};\n`;
writeFileSync(join(root, "worker/src/fixture-data.ts"), out);
console.log("Embedded fixtures", combined.split("\n").length, "lines");
